import { mkdir, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { Scanner } from '@tailwindcss/oxide';
import { compile } from '@tailwindcss/node';

const root = process.cwd();
const source = `
  @import "tailwindcss";
  @import "tw-animate-css";
`;

const scanner = new Scanner({
  sources: [
    {
      base: root,
      pattern: 'src/**/*.{js,ts,jsx,tsx}',
      negated: false,
    },
  ],
});

const candidates = scanner.scan();
const compiler = await compile(source, {
  base: root,
  onDependency() {},
});
const css = compiler.build(candidates);
const output = path.join(root, 'src', 'styles', 'generated-tailwind.css');

await mkdir(path.dirname(output), { recursive: true });
await writeFile(output, `/* Generated by scripts/generate-tailwind.mjs. */\n${css}`);

console.log(`Generated Tailwind CSS from ${candidates.length} candidates.`);
